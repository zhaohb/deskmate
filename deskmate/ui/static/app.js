function formatMeetingTime(start, end) {
  const s = start ? new Date(start) : null;
  if (!s || Number.isNaN(s.getTime())) return "(unknown time)";
  const fmt = (d) => d.toLocaleString(undefined, {
    month: "short", day: "numeric", hour: "2-digit", minute: "2-digit",
  });
  const e = end ? new Date(end) : null;
  if (!e || Number.isNaN(e.getTime())) return `${fmt(s)} → (ongoing)`;
  return `${fmt(s)} → ${e.toLocaleTimeString(undefined, { hour: "2-digit", minute: "2-digit" })}`;
}

