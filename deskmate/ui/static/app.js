async function loadTodos() {
  const query = buildTodoRangeQueryParams();
  const payload = await api(`/todos${query}`);
  state.todos = payload.data || [];
  renderTodos(payload);
}

function renderTodos(payload) {
  const list = $("#todosList");
  const countEl = $("#todosOpenCount");
  if (!list) return;
  if (countEl) {
    const open = payload?.open ?? state.todos.filter((t) => t.status !== "done").length;
    countEl.textContent = open ? `· ${open} open` : "";
  }
  list.innerHTML = "";
  if (!state.todos.length) {
    list.classList.add("empty");
    const rangeHint = todoTimeRangeUi.preset === "all"
      ? ""
      : " for the selected time range";
    list.textContent = todosUi.filter === "open"
      ? `当前没有未完成的待办${rangeHint}。请前往 Apps → Todo List Assistant 生成，或将时间范围改为「全部」。`
      : `当前没有待办${rangeHint}。请前往 Apps → Todo List Assistant 生成，或将时间范围改为「全部」。`;
    return;
  }
  list.classList.remove("empty");
  for (const todo of state.todos) {
    list.appendChild(renderTodoRow(todo));
  }
}

function renderTodoRow(todo) {
  const row = document.createElement("div");
  row.className = "todo-row" + (todo.status === "done" ? " done" : "");

  const cb = document.createElement("input");
  cb.type = "checkbox";
  cb.className = "todo-check";
  cb.checked = todo.status === "done";
  cb.addEventListener("change", () => toggleTodo(todo.id, cb.checked));

  const main = document.createElement("div");
  main.className = "todo-main";
  const text = document.createElement("div");
  text.className = "todo-text";
  text.textContent = todo.text;
  main.appendChild(text);

  const bits = [];
  if (todo.source_ref) bits.push(todo.source_ref);
  if (todo.due && todo.due.toLowerCase() !== "no date") bits.push(`due ${todo.due}`);
  if (todo.source_detail) bits.push(todo.source_detail);
  if (todo.evidence_start && todo.evidence_end) {
    bits.push(`window ${formatTime(todo.evidence_start)} – ${formatTime(todo.evidence_end)}`);
  }
  if (bits.length) {
    const meta = document.createElement("div");
    meta.className = "todo-meta";
    meta.textContent = bits.join(" · ");
    main.appendChild(meta);
  }

  const right = document.createElement("div");
  right.className = "todo-right";
  if (todo.priority) {
    const pri = document.createElement("span");
    pri.className = `todo-priority p-${todo.priority}`;
    pri.textContent = todo.priority;
    right.appendChild(pri);
  }
  const del = document.createElement("button");
  del.type = "button";
  del.className = "todo-del";
  del.title = "Delete todo";
  del.setAttribute("aria-label", "Delete todo");
  del.textContent = "×";
  del.addEventListener("click", () => deleteTodo(todo.id));
  right.appendChild(del);

  row.append(cb, main, right);
  return row;
}

async function toggleTodo(id, done) {
  try {
    await api(`/todos/${id}`, {
      method: "PATCH",
      body: JSON.stringify({ status: done ? "done" : "open" }),
    });
  } catch (err) {
    showError(err);
  }
  await loadTodos();
}

async function deleteTodo(id) {
  try {
    await api(`/todos/${id}`, { method: "DELETE" });
  } catch (err) {
    showError(err);
  }
  await loadTodos();
}

