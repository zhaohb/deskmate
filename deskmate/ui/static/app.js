async function runSearch(event) {
  event.preventDefault();
  const q = $("#homeSearchInput")?.value?.trim();
  if (!q) {
    clearHomeSearch();
    return;
  }
  setView("overview");
  setHomeSearchVisible(true);

  const answer = $("#homeAskAnswer");
  const toolLog = $("#homeAskToolLog");
  const stats = $("#homeAskStats");
  const feedback = $("#homeAskFeedback");
  const thinking = $("#homeAskThinking");
  const thinkingBody = $("#homeAskThinkingBody");

  if (answer) { answer.innerHTML = `<div class="ask-loading"><span class="ask-spinner"></span>${T("ask.thinkingSearching")}</div>`; answer.classList.remove("hidden"); }
  if (toolLog) { toolLog.innerHTML = ""; toolLog.classList.add("hidden"); }
  if (feedback) { feedback.innerHTML = ""; feedback.classList.add("hidden"); }
  if (thinking) { thinking.classList.add("hidden"); }
  if (thinkingBody) { thinkingBody.textContent = ""; }
  if (stats) stats.textContent = T("ask.searching");

  try {
    // Stream the answer: tokens render live as the model writes them, then the
    // authoritative (grounding-gated) result replaces the live text on "done".
    let streamed = "";
    let thought = "";
    let result = null;
    let started = false;
    await streamNdjson("/ask/stream", { question: q }, (m) => {
      if (m.type === "thinking") {
        // The model's reasoning pass — show it live in its own collapsible area.
        thought += m.text;
        if (thinking && thinkingBody) {
          thinking.classList.remove("hidden");
          thinkingBody.textContent = thought;
          // keep the thinking view pinned to the latest line as it streams
          thinkingBody.scrollTop = thinkingBody.scrollHeight;
        }
      } else if (m.type === "token") {
        if (!started) { started = true; if (stats) stats.textContent = T("ask.answering"); }
        streamed += m.text;
        if (answer) {
          answer.innerHTML = markdownToHtml(streamed);
          answer.classList.remove("hidden");
        }
      } else if (m.type === "reset") {
        // The model rambled before calling a tool (or we retried); the streamed
        // partial is abandoned. Clear the live preview so the user doesn't see
        // the discarded text linger until the grounded answer arrives.
        streamed = "";
        started = false;
        if (answer) {
          answer.innerHTML = `<div class="ask-loading"><span class="ask-spinner"></span>${T("ask.thinkingSearching")}</div>`;
        }
        if (stats) stats.textContent = T("ask.searching");
      } else if (m.type === "done") {
        result = m;
      } else if (m.type === "error") {
        result = { error: m.error };
      }
    });

    if (!result) result = { answer: streamed };

    if (result.error) {
      if (stats) stats.textContent = "Error";
      if (answer) { answer.innerHTML = `<div class="ask-error">Ask failed: ${escHtml(result.error)}</div>`; answer.classList.remove("hidden"); }
      return;
    }

    if (stats) {
      const n = (result.tool_calls || []).length;
      stats.textContent = n > 0 ? `${n} tool call(s)` : "Answered";
    }

    if (answer) {
      // Authoritative grounded answer (may differ from streamed preview).
      answer.innerHTML = markdownToHtml(result.answer || streamed || "(No matching data found)");
      answer.classList.remove("hidden");
    }

    if (toolLog && result.tool_calls && result.tool_calls.length > 0) {
      toolLog.innerHTML = renderToolLog(result.tool_calls);
      toolLog.classList.remove("hidden");
    }

    if (feedback && result.ask_id && !result.error) {
      renderAskFeedback(feedback, result.ask_id);
    }
  } catch (err) {
    if (stats) stats.textContent = "Error";
    if (answer) { answer.innerHTML = `<div class="ask-error">Ask failed: ${escHtml(err.message)}</div>`; answer.classList.remove("hidden"); }
  }
}

