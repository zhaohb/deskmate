function formatUptime(seconds) {
  if (seconds == null || Number.isNaN(seconds)) return "";
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  if (h > 0) return `${h}h ${m}m`;
  return `${m}m`;
}

function buildActivityFeed() {
  const items = [];
  for (const frame of state.recentFrames || []) {
    items.push({
      kind: "screen",
      ts: frame.timestamp,
      title: frame.app_name || "unknown",
      preview: textPreview(frame.accessibility_text || frame.window_name || frame.ocr_text),
      onClick: () => selectFrame(frame.id || frame.frame_id),
    });
  }
  for (const t of state.recentTranscripts || []) {
    items.push({
      kind: "audio",
      ts: t.timestamp,
      title: t.device || "mic",
      preview: textPreview(t.transcription || t.redacted_transcription),
      onClick: () => selectTranscript(t),
    });
  }
  for (const ev of state.recentEvents || []) {
    items.push({
      kind: "event",
      ts: ev.timestamp,
      title: ev.event_type || "event",
      preview: textPreview(`${ev.app_name || ""} · ${ev.window_title || ""}`),
      onClick: () => selectEvent(ev),
    });
  }
  return items
    .filter((x) => x.ts)
    .sort((a, b) => new Date(b.ts).getTime() - new Date(a.ts).getTime())
    .slice(0, 15);
}

