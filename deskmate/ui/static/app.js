function readTodoCustomRange() {
  const start = parseDatetimeLocalValue($("#todoRangeStart")?.value);
  const end = parseDatetimeLocalValue($("#todoRangeEnd")?.value);
  if (!start || !end) return { error: "请填写开始和结束时间" };
  if (start >= end) return { error: "开始时间必须早于结束时间" };
  return { startIso: toLocalIsoString(start), endIso: toLocalIsoString(end) };
}

function buildTodoRangeQueryParams() {
  const filter = todosUi.filter;
  const params = new URLSearchParams();
  if (filter && filter !== "all") params.set("status", filter);
  if (todoTimeRangeUi.preset === "all") {
    return params.toString() ? `?${params}` : "";
  }
  if (todoTimeRangeUi.preset === "custom") {
    const custom = readTodoCustomRange();
    if (!custom.error) {
      params.set("since", custom.startIso);
      params.set("until", custom.endIso);
    }
  } else {
    const range = hoursRangeFromPreset(todoTimeRangeUi.preset);
    if (range) {
      params.set("since", range.startIso);
      params.set("until", range.endIso);
    }
  }
  return params.toString() ? `?${params}` : "";
}

function updateTodoRangeSummary() {
  const summary = $("#todoRangeSummary");
  if (!summary) return;
  if (todoTimeRangeUi.preset === "all") {
    summary.textContent = "筛选：显示全部待办";
    return;
  }
  if (todoTimeRangeUi.preset === "custom") {
    const custom = readTodoCustomRange();
    summary.textContent = custom.error
      ? custom.error
      : `筛选时段：${formatVideoExportRange(custom.startIso, custom.endIso)}`;
    return;
  }
  const range = hoursRangeFromPreset(todoTimeRangeUi.preset);
  summary.textContent = range
    ? `筛选时段：${formatVideoExportRange(range.startIso, range.endIso)}`
    : "—";
}

function setTodoRangePreset(preset) {
  todoTimeRangeUi.preset = preset;
  for (const btn of document.querySelectorAll("#todoRangePresets .modal-preset")) {
    btn.classList.toggle("active", btn.dataset.preset === preset);
  }
  const custom = $("#todoCustomRange");
  if (custom) custom.classList.toggle("hidden", preset !== "custom");
  if (preset === "custom") {
    const range = hoursRangeFromPreset("16");
    if (range) {
      const startInput = $("#todoRangeStart");
      const endInput = $("#todoRangeEnd");
      if (startInput) startInput.value = toDatetimeLocalValue(new Date(range.startIso));
      if (endInput) endInput.value = toDatetimeLocalValue(new Date(range.endIso));
    }
  }
  updateTodoRangeSummary();
  loadTodos().catch(showError);
}

