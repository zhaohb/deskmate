  box.innerHTML =
    `<span class="ask-fb-q">${T("ask.fb.q")}</span>` +
    `<button type="button" class="ghost" data-act="up">${T("ask.fb.up")}</button>` +
    `<button type="button" class="ghost" data-act="down">${T("ask.fb.down")}</button>`;
