function capFmtTime(ts) {
  try { return new Date(ts).toLocaleString("en-US", { hour12: false }); }
  catch { return ts; }
}
function capEscape(s) {
  return (s || "").replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

async function loadCaptureControl() {
  const j = await api("/capture/control");
  const c = j.control || {};
  const pill = $("#capStatusPill");
  if (pill) {
    if (c.paused) { pill.className = "cap-pill paused"; pill.textContent = "● 已暂停"; }
    else { pill.className = "cap-pill live"; pill.textContent = "● 录制中"; }
  }
  const until = $("#capPauseUntil");
  if (until) until.textContent = c.paused && c.pause_until ? `Auto-resume at ${capFmtTime(c.pause_until)}` : "";

  const box = $("#capSources");
  if (!box) return;
  box.innerHTML = (j.sources || []).map((src) => {
    const on = !!c[src];
    return `<div class="cap-src ${on ? "on" : "off"}" data-src="${src}">
      <span class="dot"></span><span>${CAP_SRC_LABEL[src] || src}</span>
      <span class="muted" style="margin-left:auto">${on ? "On" : "Off"}</span>
    </div>`;
  }).join("");
  for (const el of box.querySelectorAll(".cap-src")) {
    el.onclick = () => toggleCaptureSource(el.dataset.src, el.classList.contains("off"));
  }
}

