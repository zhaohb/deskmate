// Coalesce bursts of events into at most one refresh per section per window.
const _sectionTimers = {};
function scheduleSection(name, fn, delay = 700) {
  if (_sectionTimers[name]) return;
  _sectionTimers[name] = setTimeout(() => {
    _sectionTimers[name] = null;
    fn().catch((e) => console.error("[stream]", name, e));
  }, delay);
}

let _eventStream = null;
let _streamReconnectTimer = null;

function scheduleStreamReconnect() {
  if (_streamReconnectTimer || document.hidden) return;
  _streamReconnectTimer = setTimeout(() => {
    _streamReconnectTimer = null;
    connectEventStream();
  }, 5000);
}

function connectEventStream() {
  if (document.hidden) return;
  if (_streamReconnectTimer) {
    clearTimeout(_streamReconnectTimer);
    _streamReconnectTimer = null;
  }
  try {
    _eventStream = new EventSource("/events/stream");
  } catch (e) {
    console.error("[stream] open failed", e);
    scheduleStreamReconnect();
    return;
  }
  _eventStream.onmessage = (msg) => {
    let payload;
    try {
      payload = JSON.parse(msg.data);
    } catch {
      return;
    }
    const type = payload && payload.type;
    if (!type) return;
    // Any event means the daemon is alive — keep counts/status fresh (cheap).
    scheduleSection("health", refreshHealthSection, 1500);
    // When the Capture view is open, live-refresh its unified timeline + breakdown.
    if (captureViewActive()) {
      scheduleSection("capture", () => Promise.all([
        loadUnifiedTimeline().catch((e) => console.error("[capture]", e)),
        loadTimelineBreakdown().catch((e) => console.error("[capture]", e)),
      ]), 1200);
    }
    if (
      type === "frame_written" ||
      type === "window_focus" ||
      type === "title_change" ||
      type === "a11y_written"
    ) {
      scheduleSection("frames", refreshFramesSection);
    } else if (type === "audio_transcribed") {
      scheduleSection("transcripts", refreshTranscriptsSection);
      onTranslateTranscribed(payload.data || {});
    } else if (type === "transcript_translated") {
      // Live translation arrived for a transcript: try to patch the visible row
      // in place (no flicker); fall back to a section refresh if it isn't shown.
      if (!applyTranslationToRow(payload.data || {})) {
        scheduleSection("transcripts", refreshTranscriptsSection);
      }
      onTranslateTranslated(payload.data || {});
    } else if (
      type === "click" ||
      type === "key_text" ||
      type === "clipboard" ||
      type === "value_change"
    ) {
      scheduleSection("events", refreshEventsSection);
    }
  };
  _eventStream.onerror = () => {
    if (_eventStream) {
      _eventStream.close();
      _eventStream = null;
    }
    scheduleStreamReconnect();
  };
}

function disconnectEventStream() {
  if (_eventStream) {
    _eventStream.close();
    _eventStream = null;
  }
  if (_streamReconnectTimer) {
    clearTimeout(_streamReconnectTimer);
    _streamReconnectTimer = null;
  }
}

